const CACHE = "reading-den-" + VERSION;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) =>
      // One missing file must not stop the rest being cached.
      Promise.all(PRECACHE.map((url) => cache.add(url).catch(() => {})))
    ).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE && k.startsWith("reading-den-")).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Safari asks for audio in byte ranges and won't play a plain 200 reply to
// one, so cut the cached file down to the range it asked for.
async function rangeResponse(request, response) {
  const buffer = await response.arrayBuffer();
  const match = /bytes=(\d*)-(\d*)/.exec(request.headers.get("range"));
  const start = match && match[1] ? parseInt(match[1], 10) : 0;
  const end = match && match[2] ? Math.min(parseInt(match[2], 10), buffer.byteLength - 1) : buffer.byteLength - 1;
  return new Response(buffer.slice(start, end + 1), {
    status: 206,
    statusText: "Partial Content",
    headers: {
      "Content-Type": response.headers.get("Content-Type") || "audio/mpeg",
      "Content-Range": "bytes " + start + "-" + end + "/" + buffer.byteLength,
      "Content-Length": String(end - start + 1)
    }
  });
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin) return;

  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // Range requests carry a Range header that must not be part of the key.
    const key = new Request(request.url);
    const cached = await cache.match(key);
    const isAudio = /\.mp3$/.test(url.pathname);

    const fromNetwork = () => fetch(key).then((response) => {
      if (response.ok) cache.put(key, response.clone());
      return response;
    });

    if (cached) {
      // Audio never changes under the same name; everything else is
      // refreshed behind the scenes for next time.
      if (!isAudio) fromNetwork().catch(() => {});
      return request.headers.get("range") ? rangeResponse(request, cached.clone()) : cached;
    }
    try {
      const response = await fromNetwork();
      return request.headers.get("range") && response.ok ? rangeResponse(request, response.clone()) : response;
    } catch (e) {
      // Offline and not cached: fall back to the home page for navigations.
      if (request.mode === "navigate") {
        const home = await cache.match(new Request(new URL("index.html", self.registration.scope).href));
        if (home) return home;
      }
      return Response.error();
    }
  })());
});
